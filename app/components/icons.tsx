/** Maps an Open-Meteo WMO weather code to the matching condition emoji. */
function weatherEmoji(code: number): string {
  if (code === 0 || code === 1) return "☀️";
  if (code === 2) return "⛅";
  if (code === 3) return "☁️";
  if (code === 45 || code === 48) return "🌫️";
  if (code >= 95) return "⛈️";
  if ((code >= 71 && code <= 77) || code === 85 || code === 86) return "🌨️";
  if ((code >= 51 && code <= 67) || code === 80 || code === 81 || code === 82) return "🌧️";
  return "⛅";
}

export function WeatherConditionIcon({ code, size = 44, className }: IconProps & { code: number }) {
  return (
    <span role="img" aria-hidden="true" className={className} style={{ fontSize: size, lineHeight: 1, display: "inline-block" }}>
      {weatherEmoji(code)}
    </span>
  );
}
